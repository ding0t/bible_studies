"""The words the ULT and the Berean Interlinear render differently most often, across the canon.

Runs query.lookup_alignment_diff over every chapter both alignments cover, totals each compared
word by its Strong's number, and writes the ranking to docs/dev/alignment-disagreements.md. It is
a list of terms a word study should always check: where two independent committees keep choosing
different English for the same Hebrew or Greek word, a study resting on one English rendering is
resting on a translator's choice.

The ranking does not judge. Many top entries are synonyms ("empty"/"void"), and the table prints
each side's commonest renderings so a reader sees at once whether the disagreement is in meaning
or only in wording. Run from references/build:

    uv run python alignment_ranking.py            # writes the report
    uv run python alignment_ranking.py --min 30   # only words compared at least 30 times
"""

from __future__ import annotations

import argparse
import re
import sqlite3
from collections import Counter, defaultdict
from pathlib import Path

import query

REPORT = Path(__file__).resolve().parents[2] / "docs" / "dev" / "alignment-disagreements.md"


def lemmas(conn: sqlite3.Connection) -> dict[str, tuple[str, str]]:
    """Strong's number -> (lemma, commonest gloss), from MACULA, keyed as the Berean writes it."""
    found: dict[str, Counter] = defaultdict(Counter)
    lemma_of: dict[str, str] = {}
    for work, number, lemma, gloss in conn.execute(
            "SELECT work_id, strongs_id, lemma, gloss FROM morphology WHERE work_id LIKE 'macula-%' "
            "AND strongs_id GLOB '[0-9]*' AND strongs_id NOT LIKE '%+%'"):
        digits = re.match(r"\d+", number).group().lstrip("0")
        if not digits:
            continue
        # MACULA splits homographs with a letter (H197a); the Berean writes the bare number.
        sid = ("G" if "greek" in work else "H") + digits
        lemma_of.setdefault(sid, lemma or "")
        if gloss:
            found[sid][gloss.lower().replace(".", " ")] += 1
    return {sid: (lemma_of[sid], found[sid].most_common(1)[0][0] if found[sid] else "") for sid in lemma_of}


def run(conn: sqlite3.Connection) -> list[tuple]:
    tally: list = []
    chapters = conn.execute(
        "SELECT book, chapter, MAX(verse) FROM word_alignment WHERE work_id='berean-bib' "
        "GROUP BY book, chapter ORDER BY MIN(rowid)").fetchall()
    for book, chapter, last in chapters:
        query.lookup_alignment_diff(conn, book, chapter, 1, last, tally=tally)
    return tally


def rank(tally: list[tuple], minimum: int) -> list[dict]:
    by_word: dict[str, dict] = defaultdict(lambda: {"n": 0, "differ": 0, "ult": Counter(), "bsb": Counter()})
    for strong, same, ult, bsb in tally:
        if not strong:
            continue
        w = by_word[strong]
        w["n"] += 1
        if not same:
            w["differ"] += 1
            w["ult"][ult] += 1
            w["bsb"][bsb] += 1
    rows = [{"strong": s, **w} for s, w in by_word.items() if w["n"] >= minimum and w["differ"]]
    rows.sort(key=lambda r: (-r["differ"] / r["n"], -r["differ"], r["strong"]))
    return rows


def write(rows: list[dict], lex: dict, tally: list, minimum: int, top: int) -> str:
    compared = len(tally)
    differ = sum(1 for t in tally if not t[1])
    def renderings(c: Counter) -> str:
        return "; ".join(f"{e} ({n})" for e, n in c.most_common(3))
    lines = [
        "# Where the ULT and the Berean render a word differently",
        "",
        "Generated by `references/build/alignment_ranking.py`; re-run it after `build.py`, do not edit",
        "by hand. Not part of the published site.",
        "",
        f"Across the canon {compared:,} original words were rendered with content words by both the",
        f"ULT and the Berean Interlinear, and {differ:,} ({differ / compared:.1%}) share no content word.",
        f"Below are the {top} words compared at least {minimum} times that differ most often, by rate.",
        "",
        "**This is a list to check, never a verdict.** Many entries are synonyms, and a reader can see",
        "which from the renderings. Where the two committees keep choosing different English for one",
        "word, a study resting on one rendering rests on a translator's choice: check the word in its",
        "lexicon and its uses before arguing from the English (develop-bible-study, Phase 4).",
        "",
        "Strong's numbers are the Berean's. Word and Gloss come from MACULA; a blank means MACULA files",
        "the word under another number (it puts אוּלָם, porch, at H199 where the Berean has H197).",
        "",
        "| Strong's | Word | Gloss | Compared | Differ | ULT's commonest when they differ | BSB's commonest when they differ |",
        "|---|---|---|---:|---:|---|---|",
    ]
    for r in rows[:top]:
        lemma, gloss = lex.get(r["strong"], ("", ""))
        lines.append(f"| {r['strong']} | {lemma} | {gloss} | {r['n']} | {r['differ'] / r['n']:.0%} | "
                     f"{renderings(r['ult'])} | {renderings(r['bsb'])} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--min", type=int, default=20, help="only words compared at least this often")
    parser.add_argument("--top", type=int, default=150)
    args = parser.parse_args()
    conn = query.connect()
    tally = run(conn)
    rows = rank(tally, args.min)
    REPORT.write_text(write(rows, lemmas(conn), tally, args.min, args.top), encoding="utf-8")
    print(f"{len(tally):,} words compared; {len(rows)} words differ at least once -> {REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
